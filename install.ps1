# 一键幂等安装 FaceFusion（V100/Volta + Windows + 大陆网络 专用版）
# 用法：powershell -ExecutionPolicy Bypass -File .\install.ps1 [-InstallRoot D:\FaceFusion]
param(
    [string]$InstallRoot = 'D:\FaceFusion'
)

$ErrorActionPreference = 'Continue'
$RepoRoot = $PSScriptRoot
$VenvScripts = Join-Path $InstallRoot '.venv\Scripts'
$VenvPython = Join-Path $VenvScripts 'python.exe'
$WinGetLinks = Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Links'

function Step($msg) { Write-Host "`n=== $msg ===" -ForegroundColor Cyan }
function Ok($msg)   { Write-Host "  [OK] $msg" -ForegroundColor Green }
function Warn($msg) { Write-Host "  [!!] $msg" -ForegroundColor Yellow }

Step '1/9 前置检查：python / git / winget / uv'
if (-not (Get-Command git -ErrorAction SilentlyContinue)) {
    throw 'git 未安装，请先安装 Git for Windows'
}
if (-not (Get-Command python -ErrorAction SilentlyContinue)) {
    Write-Host '  python 缺失，尝试 winget 安装 Python 3.12 ...'
    winget install --id Python.Python.3.12 -e --accept-source-agreements --accept-package-agreements --disable-interactivity
}
if (-not (Get-Command uv -ErrorAction SilentlyContinue)) {
    Write-Host '  uv 缺失，通过 pip 安装 ...'
    python -m pip install -q uv
    if (-not (Get-Command uv -ErrorAction SilentlyContinue)) { throw 'uv 安装失败' }
}
Ok "git / python / uv 就绪"

Step '2/9 安装 FFmpeg（winget，若已装则跳过）'
$ffmpegOnPath = (Get-Command ffmpeg -ErrorAction SilentlyContinue) -or (Test-Path (Join-Path $WinGetLinks 'ffmpeg.exe'))
if ($ffmpegOnPath) { Ok 'FFmpeg 已存在' }
else {
    winget install --id Gyan.FFmpeg -e --accept-source-agreements --accept-package-agreements --disable-interactivity
    Ok 'FFmpeg 安装完成（注意：新 PATH 要新进程才生效，本脚本已手动注入）'
}

Step "3/9 克隆 FaceFusion 到 $InstallRoot"
if (Test-Path (Join-Path $InstallRoot 'facefusion.py')) {
    Ok '目录已存在，跳过克隆'
} else {
    $cloned = $false
    for ($i = 1; $i -le 3; $i++) {
        git clone --depth 1 https://github.com/facefusion/facefusion.git $InstallRoot
        if ($LASTEXITCODE -eq 0 -and (Test-Path (Join-Path $InstallRoot 'facefusion.py'))) { $cloned = $true; break }
        Warn "克隆失败（第 $i 次），网络可能不稳，10 秒后重试..."
        Start-Sleep -Seconds 10
    }
    if (-not $cloned) { throw 'FaceFusion 克隆失败，请检查网络后重跑本脚本（幂等）' }
}
Ok '源码就绪'

Step '4/9 创建 Python 3.12 虚拟环境（不要用系统 3.13，见 PITFALLS #9）'
if (Test-Path $VenvPython) { Ok 'venv 已存在' }
else {
    for ($i = 1; $i -le 3; $i++) {
        uv venv "$InstallRoot\.venv" --python 3.12
        if ($LASTEXITCODE -eq 0 -and (Test-Path $VenvPython)) { break }
        Warn "uv venv 失败（第 $i 次，可能是下载 3.12 时网络抖动），重试..."
        Start-Sleep -Seconds 10
    }
    if (-not (Test-Path $VenvPython)) { throw 'venv 创建失败' }
}
Ok 'venv 就绪'

Step '5/9 安装 FaceFusion 依赖 + 锁定版本（顺序重要，见 PITFALLS #1/#4）'
# 先装上游依赖，再覆盖安装 GPU 版 onnxruntime（后装者覆盖同名 capi 文件）
uv pip install -p $VenvPython -r (Join-Path $InstallRoot 'requirements.txt')
uv pip install -p $VenvPython onnxruntime-gpu==1.20.2
uv pip install -p $VenvPython nvidia-cublas-cu12==12.9.2.10 nvidia-cuda-nvrtc-cu12==12.9.86 nvidia-cuda-runtime-cu12==12.9.79 nvidia-cudnn-cu12==9.3.0.75 nvidia-cufft-cu12==11.4.1.4 nvidia-nvjitlink-cu12==12.9.86
Ok '依赖安装完成（onnxruntime-gpu==1.20.2 + cuDNN 9.3.0.75）'

Step '6/9 下载必需模型（hf-mirror 优先，CRC32 校验）'
$env:NVIDIA_DLL_PATH = Join-Path $InstallRoot '.venv\Lib\site-packages\nvidia'
& $VenvPython (Join-Path $RepoRoot 'scripts\dl_models.py') (Join-Path $InstallRoot '.assets\models')
if ($LASTEXITCODE -ne 0) { throw '模型下载失败，请重跑本脚本（幂等，已完成的会跳过）' }

Step '7/9 写入默认配置（CUDA + 镜像源）'
& $VenvPython (Join-Path $RepoRoot 'scripts\patch_facefusion_ini.py') (Join-Path $InstallRoot 'facefusion.ini')

Step '8/9 生成启动器 StartFaceFusion.bat'
$batContent = @"
@echo off
rem FaceFusion launcher - V100 CUDA version (generated by facefusion-v100-setup)
setlocal
set VENV=$VenvScripts
set NVIDIA=$InstallRoot\.venv\Lib\site-packages\nvidia

set PATH=%VENV%;%NVIDIA%\cublas\bin;%NVIDIA%\cudnn\bin;%NVIDIA%\cufft\bin;%NVIDIA%\cuda_runtime\bin;%NVIDIA%\nvjitlink\bin;%NVIDIA%\cuda_nvrtc\bin;$WinGetLinks;%PATH%

cd /d $InstallRoot
python facefusion.py run
pause
"@
Set-Content -Path (Join-Path $InstallRoot 'StartFaceFusion.bat') -Value $batContent -Encoding ASCII
Ok (Join-Path $InstallRoot 'StartFaceFusion.bat')

Step '9/9 冒烟测试（真实换脸，验证 CUDA 全链路）'
$sp = Join-Path $InstallRoot '.venv\Lib\site-packages\nvidia'
$env:Path = "$VenvScripts;$sp\cublas\bin;$sp\cudnn\bin;$sp\cufft\bin;$sp\cuda_runtime\bin;$sp\nvjitlink\bin;$sp\cuda_nvrtc\bin;$WinGetLinks;" + $env:Path

& $VenvPython (Join-Path $RepoRoot 'scripts\test_cuda.py')
if ($LASTEXITCODE -ne 0) { throw 'CUDA EP 探活失败，见 PITFALLS.md #3' }
& $VenvPython (Join-Path $RepoRoot 'scripts\test_cudnn.py') (Join-Path $InstallRoot '.assets\models\yoloface_8n.onnx')
if ($LASTEXITCODE -ne 0) { throw '真实模型推理失败，见 PITFALLS.md #1/#2' }

& $VenvPython (Join-Path $RepoRoot 'scripts\dl_examples.py') (Join-Path $InstallRoot '.assets\examples')
Set-Location $InstallRoot
$smokeOut = Join-Path $env:TEMP 'facefusion_smoke.mp4'
python facefusion.py headless-run -s .assets\examples\source.jpg -t .assets\examples\target-240p.mp4 -o $smokeOut --processors face_swapper --execution-providers cuda --download-providers huggingface
$smokeOk = (Test-Path $smokeOut) -and ((Get-Item $smokeOut).Length -gt 100KB)
if ($smokeOk) {
    Ok "冒烟测试通过：$smokeOut ($([math]::Round((Get-Item $smokeOut).Length/1KB)) KB)"
    Write-Host "`n=== 安装全部完成 ===" -ForegroundColor Green
    Write-Host "双击 $InstallRoot\StartFaceFusion.bat 开始使用"
    Write-Host "详细说明：$InstallRoot\使用说明.md"
    exit 0
} else {
    throw '冒烟测试未产出视频，见 PITFALLS.md（注意：PowerShell 可能把进度条当错误显示，以本文件是否存在为准）'
}
